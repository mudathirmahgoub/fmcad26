#!/usr/bin/env python3

"""
Generate every benchmark file under benchmarks/ from its source.

    python3 generate_benchmarks.py [--only sets|bags|sql] [--jobs N]
                                   [--sql-source DIR]

int.star-contains no longer assumes nonnegative summand vectors (the
ARITH_LIA_STAR_NONNEGATIVE lemma and Normaliz's ambient nonnegativity
were removed from the cvc5 liastar extension), so every lambda body in
the generated benchmarks constrains its bound variables with explicit
(>= v 0) conjuncts. All three sections are (re)generated by this script:

  sets (bapa):  benchmarks/arith/cvc5_bapa + benchmarks/card/cvc5_bapa
  bags (mapa):  benchmarks/arith/cvc5_mapa + benchmarks/card/cvc5_mapa
      Translated from the native BAPA benchmarks of the sls-reachability
      clone (sls-reachability/benchmarks/bapa/{arith,card}/fol_*.smt2)
      by its lia_star_cvc5.py, which emits the nonnegativity conjuncts
      itself.

  sql:          benchmarks/sql/linear
      Copied from the strictly-linear SQLSolver dumps (produced by
      Cvc5LiaStarSolver.java, --sql-source, default ~/SQLSolver/cvc5/
      linear; when absent, the existing benchmarks/sql/linear files are
      used as the source instead), then rewritten so that every
      int.star-contains lambda body carries the (>= v 0) conjuncts for
      its bound variables. The rewrite is idempotent -- dumps that
      already contain the conjuncts (Cvc5LiaStarSolver.java now emits
      them too) pass through unchanged -- so either source works.
"""

import argparse
import os
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor

import count_ite

FMCAD_DIR = os.path.dirname(os.path.abspath(__file__))
BENCHMARKS_DIR = os.path.join(FMCAD_DIR, "benchmarks")
SLS_DIR = os.path.join(FMCAD_DIR, "sls-reachability")
SLS_NATIVE_DIR = os.path.join(SLS_DIR, "benchmarks", "bapa")
SLS_GENERATOR = os.path.join(SLS_DIR, "lia_star_cvc5.py")
WINDOWS = os.name == "nt"
SLS_PYTHON = os.path.join(
    SLS_DIR, ".venv",
    *(("Scripts", "python.exe") if WINDOWS else ("bin", "python3")))
DEFAULT_SQL_SOURCE = os.path.join(
    os.path.expanduser("~"), "SQLSolver", "cvc5", "linear")

NATIVE_NAMES = ["fol_{:07d}.smt2".format(i) for i in range(1, 121)]


# ---------------------------------------------------------------------------
# sets/bags: translate the native BAPA benchmarks with lia_star_cvc5.py
# ---------------------------------------------------------------------------

def generate_native(family, mode, name):
    """Translate one native benchmark. lia_star_cvc5.py writes its output
    next to the input (bapa/<family>/cvc5_<mode>/<name>); move it to
    benchmarks/<family>/cvc5_<mode>/<name>."""
    native = os.path.join(SLS_NATIVE_DIR, family, name)
    produced = os.path.join(SLS_NATIVE_DIR, family, "cvc5_" + mode, name)
    target_dir = os.path.join(BENCHMARKS_DIR, family, "cvc5_" + mode)
    cmd = [SLS_PYTHON, SLS_GENERATOR, native]
    if mode == "mapa":
        cmd.append("--mapa")
    proc = subprocess.run(cmd, capture_output=True, cwd=SLS_DIR)
    if proc.returncode != 0 or not os.path.exists(produced):
        raise RuntimeError("translation failed for {} ({}):\n{}".format(
            native, mode, proc.stderr.decode("utf-8", "replace")[-2000:]))
    shutil.move(produced, os.path.join(target_dir, name))
    return "{}/cvc5_{}/{}".format(family, mode, name)


def generate_sets_bags(jobs):
    tasks = [(family, mode, name)
             for family in ("arith", "card")
             for mode in ("bapa", "mapa")
             for name in NATIVE_NAMES]
    for family in ("arith", "card"):
        for mode in ("bapa", "mapa"):
            os.makedirs(os.path.join(SLS_NATIVE_DIR, family, "cvc5_" + mode),
                        exist_ok=True)
            os.makedirs(os.path.join(BENCHMARKS_DIR, family, "cvc5_" + mode),
                        exist_ok=True)
    print("translating {} native benchmarks ({} jobs)".format(
        len(tasks), jobs), flush=True)
    with ThreadPoolExecutor(max_workers=jobs) as pool:
        for done, _ in enumerate(
                pool.map(lambda t: generate_native(*t), tasks), 1):
            if done % 80 == 0 or done == len(tasks):
                print("  {}/{}".format(done, len(tasks)), flush=True)


# ---------------------------------------------------------------------------
# sql: rewrite the SQLSolver linear dumps
# ---------------------------------------------------------------------------

def add_nonneg(tree):
    """Recursively give every (int.star-contains (lambda ...) ...) body
    the (>= v 0) conjuncts for its bound variables (idempotent)."""
    if not isinstance(tree, list):
        return
    if (len(tree) >= 2 and tree[0] == "int.star-contains"
            and isinstance(tree[1], list) and len(tree[1]) == 3
            and tree[1][0] == "lambda"):
        bound = [binding[0] for binding in tree[1][1]]
        body = tree[1][2]
        conjuncts = (body[1:] if isinstance(body, list) and body
                     and body[0] == "and" else [body])
        existing = {count_ite.render(c) for c in conjuncts}
        needed = [[">=", v, "0"] for v in bound
                  if "(>= {} 0)".format(v) not in existing]
        if needed:
            tree[1][2] = ["and"] + needed + conjuncts
    for child in tree:
        add_nonneg(child)


def rewrite_sql_file(source, target):
    with open(source) as f:
        text = f.read()
    # the dump header comments (provenance / weakening warnings) survive
    # the rewrite; the command bodies are re-rendered
    comments = [line for line in text.splitlines()
                if line.lstrip().startswith(";")]
    commands = count_ite.parse(count_ite.tokenize(text))
    for command in commands:
        add_nonneg(command)
    with open(target, "w") as f:
        for line in comments:
            f.write(line + "\n")
        for command in commands:
            f.write(count_ite.render(command) + "\n")


def generate_sql(sql_source):
    target_dir = os.path.join(BENCHMARKS_DIR, "sql", "linear")
    if os.path.isdir(sql_source):
        source_dir = sql_source
    else:
        print("sql source {} not found; rewriting benchmarks/sql/linear "
              "in place".format(sql_source), flush=True)
        source_dir = target_dir
    names = sorted(f for f in os.listdir(source_dir) if f.endswith(".smt2"))
    if not names:
        sys.exit("error: no smt2 files in {}".format(source_dir))
    os.makedirs(target_dir, exist_ok=True)
    print("rewriting {} sql benchmarks from {}".format(
        len(names), source_dir), flush=True)
    for name in names:
        rewrite_sql_file(os.path.join(source_dir, name),
                         os.path.join(target_dir, name))


def main():
    p = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--only", choices=["sets", "bags", "sql"], default=None,
                   help="generate only one section (sets and bags share "
                        "the translation step; default: everything)")
    p.add_argument("--jobs", type=int, default=8,
                   help="parallel translation jobs (default: 8)")
    p.add_argument("--sql-source", default=DEFAULT_SQL_SOURCE,
                   help="directory with the strictly-linear SQLSolver "
                        "dumps (default: {})".format(DEFAULT_SQL_SOURCE))
    args = p.parse_args()

    if args.only in (None, "sets", "bags"):
        if not os.path.exists(SLS_PYTHON):
            sys.exit("error: {} not found -- run python3 setup.py first"
                     .format(SLS_PYTHON))
        generate_sets_bags(args.jobs)
    if args.only in (None, "sql"):
        generate_sql(args.sql_source)

    for directory, expected in [("arith/cvc5_bapa", 120),
                                ("arith/cvc5_mapa", 120),
                                ("card/cvc5_bapa", 120),
                                ("card/cvc5_mapa", 120),
                                ("sql/linear", 29)]:
        path = os.path.join(BENCHMARKS_DIR, directory)
        count = len([f for f in os.listdir(path) if f.endswith(".smt2")])
        marker = "" if count == expected else "  <-- expected {}".format(
            expected)
        print("{:<18} {} files{}".format(directory, count, marker))


if __name__ == "__main__":
    main()
